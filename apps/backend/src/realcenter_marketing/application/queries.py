"""Read and reference-library boundary consumed by the HTTP adapter."""
from typing import Protocol, Any


class StudioQueries(Protocol):
    def runs(self, active_id: str | None) -> list[dict]: ...
    def media(self) -> list[dict]: ...
    def media_file(self, key: str) -> tuple[bytes, str]: ...
    def references(self) -> list[dict]: ...
    def reference_file(self, key: str) -> tuple[bytes, str]: ...
    def save_reference(self, request: Any) -> dict: ...
    def activity(self) -> list[dict]: ...
    def usage(self) -> dict: ...
    def artifact(self, run_id: str, name: str) -> tuple[Any, str]: ...
