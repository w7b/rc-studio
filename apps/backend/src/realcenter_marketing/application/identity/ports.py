"""Storage and crypto contracts for identity. Implementations live in infrastructure."""
from typing import Protocol

from .model import Invite, OAuthProfile, Principal, Session, Tenant, User


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, encoded: str) -> bool: ...
    def dummy_verify(self) -> None:
        """Spend the same time as a real check so a missing account cannot be told
        apart from a wrong password by timing."""


class RateLimiter(Protocol):
    def hit(self, key: str, limit: int, window_seconds: int) -> bool:
        """Record an attempt. False once the key is over its limit for the window."""

    def reset(self, key: str) -> None: ...


class IdentityStore(Protocol):
    def tenant_by_slug(self, slug: str) -> Tenant | None: ...
    def tenant(self, tenant_id: int) -> Tenant | None: ...
    def tenants(self) -> list[Tenant]: ...
    def create_tenant(self, slug: str, name: str, root_path: str | None = None) -> Tenant: ...
    def set_tenant_status(self, tenant_id: int, status: str) -> None: ...
    def members(self, tenant_id: int) -> list[tuple[User, str]]: ...
    def modules(self, tenant_id: int) -> dict[str, bool]: ...
    def set_module(self, tenant_id: int, module: str, enabled: bool) -> None: ...
    def registration_counts(self, start, end) -> dict[str, int]: ...

    def user_by_email(self, email: str) -> User | None: ...
    def user_by_id(self, user_id: int) -> User | None: ...
    def password_hash(self, user_id: int) -> str | None: ...
    def create_user(self, email: str, password_hash: str | None, name: str = '') -> User: ...
    def touch_login(self, user_id: int) -> None: ...
    def set_password(self, user_id: int, password_hash: str) -> None: ...
    def update_profile(self, user_id: int, email: str, name: str, phone: str) -> User: ...

    def user_by_identity(self, provider: str, subject: str) -> User | None: ...
    def link_identity(self, user_id: int, provider: str, subject: str) -> None: ...

    def membership(self, user_id: int, tenant_id: int) -> str | None: ...
    def memberships(self, user_id: int) -> list[tuple[Tenant, str]]: ...
    def grant(self, user_id: int, tenant_id: int, role: str) -> None: ...
    def revoke(self, user_id: int, tenant_id: int) -> None: ...

    def create_session(self, token_hash: str, user_id: int, tenant_id: int, role: str, csrf: str) -> Session: ...
    def session(self, token_hash: str) -> Session | None: ...
    def touch_session(self, token_hash: str) -> None: ...
    def drop_session(self, token_hash: str) -> None: ...
    def drop_user_sessions(self, user_id: int) -> None: ...

    def create_invite(self, token_hash: str, tenant_id: int, role: str, email: str, expires_at) -> None: ...
    def invite(self, token_hash: str) -> Invite | None: ...
    def consume_invite(self, token_hash: str) -> bool:
        """Mark the invite used. False if another request already claimed it."""


class OAuthProvider(Protocol):
    name: str

    def authorization_url(self, state: str, verifier: str, redirect_uri: str) -> str: ...
    def exchange(self, code: str, verifier: str, redirect_uri: str) -> OAuthProfile: ...
