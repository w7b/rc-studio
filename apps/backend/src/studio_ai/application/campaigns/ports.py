"""Boundaries required by campaign use cases; no SDK or storage implementation."""
from pathlib import Path
from typing import Any, Callable, Protocol

from studio_ai.application.orchestration import AgentResult
from studio_ai.domain.campaigns import Campaign, CampaignBrief


class Journal(Protocol):
    directory: Path
    current_agent: str | None

    def save(self, role: str, value: Any) -> None: ...
    def emit(self, event: str, agent: str | None = None, **details: Any) -> None: ...


class JobQueue(Protocol):
    """Durable queue bound to one tenant by the composition root."""
    def enqueue(self, kind: str, payload: dict, run_id: str) -> int: ...
    def active(self) -> list[dict]: ...
    def pending(self) -> int: ...


class AgentRuntime(Protocol):
    async def __call__(self, brief: CampaignBrief) -> AgentResult: ...


class CampaignExecutor(Protocol):
    async def __call__(self, brief: CampaignBrief, mode: str, journal: Journal,
                       model_id: str | None = None) -> Campaign: ...


class CampaignRepository(Protocol):
    def prepare_inputs(self, request: Any) -> Any: ...
    def create_run(self, request: Any, inputs: Any) -> tuple[Journal, Path | None]: ...
    def create_assist(self) -> Journal: ...
    def saved_request(self, run_id: str) -> Any: ...
    def campaign(self, run_id: str) -> Campaign: ...
    def has_campaign(self, run_id: str) -> bool: ...
    def last_event(self, run_id: str) -> str | None: ...
    def set_title(self, run_id: str, title: str) -> str: ...
    def delete(self, run_id: str) -> None: ...
    def resume(self, run_id: str) -> Journal: ...
    def usage(self, journal: Journal) -> dict | None: ...
    def product(self, run_id: str) -> Path | None: ...
    def revision_image(self, run_id: str, image_id: str) -> Path: ...
    def decode_upload(self, value: str | None) -> bytes | None: ...
    def save_revision(self, journal: Journal, content: bytes) -> Path: ...
    def image_metadata(self, image: Path) -> dict: ...
    def carousel_files(self, journal: Journal) -> dict: ...
    def existing_image(self, journal: Journal, filename: str | None) -> Path | None: ...
    def save_carousel(self, journal: Journal, batch: dict) -> None: ...


class ExecutionScheduler(Protocol):
    lock: Any

    def acquire(self) -> bool: ...
    def release(self) -> None: ...
    def submit(self, work: Callable[[], None]) -> None: ...
    def call(self, work: Callable[[], Any]) -> Any: ...
    def close(self, timeout: float | None = None) -> bool: ...


class ImageGenerator(Protocol):
    def __call__(self, campaign: Campaign, journal: Journal, product: Path | None, **options: Any) -> Path: ...
